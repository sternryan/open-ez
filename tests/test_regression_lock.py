def test_regression_baselines_not_self_referential():
    """TRACEABILITY: This test file must not load physics_baseline.json as a data source.

    physics_baseline.json is generated by the same code being tested — loading it
    as a data source creates a self-referential loop where tests can never catch
    regressions (the baseline updates with the code).

    This test reads its own source and confirms 'physics_baseline.json' does not
    appear as an import path, open() argument, or data source.

    Note: the string 'physics_baseline.json' may appear in this assertion itself
    or in comments — that is acceptable. Only data-loading usage is forbidden.
    """
    source_path = Path(__file__)
    source_text = source_path.read_text()

    # Find all lines that reference physics_baseline.json
    lines_with_baseline = [
        (i + 1, line.strip())
        for i, line in enumerate(source_text.splitlines())
        if "physics_baseline.json" in line
    ]

    # Lines that are acceptable: comments, docstrings, and this assertion itself
    # We check that no line is an actual data-loading operation (open, json.load, Path)
    forbidden_patterns = ["open(", "json.load", "Path(", "read_text", "read("]

    violations = []
    for lineno, line in lines_with_baseline:
        # Skip comment lines (start with #) and docstring content
        stripped = line.lstrip()
        if stripped.startswith("#"):
            continue
        if stripped.startswith('"""') or stripped.startswith("'''"):
            continue
        if stripped.startswith('"') or stripped.startswith("'"):
            # String literal (docstring continuation or assertion string)
            continue

        # Check if it's a data-loading operation
        for pattern in forbidden_patterns:
            if pattern in line:
                violations.append(f"  Line {lineno}: {line}")
                break

    assert not violations, (
        f"TRACEABILITY VIOLATION: test_regression_lock.py loads physics_baseline.json "
        f"as a data source. This creates a self-referential loop. "
        f"Remove these data-loading references:\n" + "\n".join(violations)
    )


def test_regression_values_match_accuracy_report():
    """TRACEABILITY: Locked constants in this file must match accuracy_report.json computed values.

    Verifies that the LOCKED_* constants defined in this module exactly match the
    corresponding computed values in accuracy_report.json. This creates a documented
    traceability link: locked constants -> accuracy report -> reference_data.json.

    If this test fails, the locked constants are out of sync with the accuracy report
    and must be updated (along with re-running Phase 5 calibration if needed).
    """
    report = _load_accuracy_report()

    # Ledger row 20: the drift locks trace to the report's computed values whatever their grade;
    # that the locked metrics still PASS external truth is test_regression_locked_metrics_all_pass.
    computed = {m["metric_id"]: m["computed"] for m in report["metrics"]}

    mismatches = []
    for metric_id, locked_value, const_name in LOCKED_CHECKS:
        assert metric_id in computed, (
            f"TRACEABILITY: Metric '{metric_id}' not found in accuracy_report.json metrics."
        )
        if locked_value != computed[metric_id]:
            mismatches.append(
                f"  {const_name} = {locked_value!r} "
                f"!= accuracy_report['{metric_id}'].computed = {computed[metric_id]!r}"
            )

    assert not mismatches, (
        f"TRACEABILITY VIOLATION: Locked constants are out of sync with accuracy_report.json.\n"
        f"Update the LOCKED_* constants to match the report computed values:\n"
        + "\n".join(mismatches)
    )


